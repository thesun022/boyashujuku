WITH actual AS (
  SELECT tc.CONSTRAINT_TYPE AS object_kind, tc.TABLE_NAME AS table_name, tc.CONSTRAINT_NAME AS object_name,
         GROUP_CONCAT(k.COLUMN_NAME ORDER BY k.ORDINAL_POSITION) AS definition
  FROM information_schema.TABLE_CONSTRAINTS tc
  JOIN information_schema.KEY_COLUMN_USAGE k USING (CONSTRAINT_SCHEMA, TABLE_NAME, CONSTRAINT_NAME)
  WHERE tc.CONSTRAINT_SCHEMA = DATABASE() AND tc.CONSTRAINT_TYPE IN ('PRIMARY KEY','UNIQUE')
  GROUP BY tc.CONSTRAINT_TYPE, tc.TABLE_NAME, tc.CONSTRAINT_NAME

  UNION ALL
  SELECT 'FOREIGN KEY', fk.TABLE_NAME, fk.CONSTRAINT_NAME,
         CONCAT(GROUP_CONCAT(k.COLUMN_NAME ORDER BY k.ORDINAL_POSITION), ' -> ',
                MAX(k.REFERENCED_TABLE_NAME), '(', GROUP_CONCAT(k.REFERENCED_COLUMN_NAME ORDER BY k.ORDINAL_POSITION), ')',
                '; DELETE ', IF(fk.DELETE_RULE IN ('RESTRICT','NO ACTION'), 'BLOCK', fk.DELETE_RULE),
                '; UPDATE ', IF(fk.UPDATE_RULE IN ('RESTRICT','NO ACTION'), 'BLOCK', fk.UPDATE_RULE))
  FROM information_schema.REFERENTIAL_CONSTRAINTS fk
  JOIN information_schema.KEY_COLUMN_USAGE k USING (CONSTRAINT_SCHEMA, TABLE_NAME, CONSTRAINT_NAME)
  WHERE fk.CONSTRAINT_SCHEMA = DATABASE()
  GROUP BY fk.TABLE_NAME, fk.CONSTRAINT_NAME, fk.DELETE_RULE, fk.UPDATE_RULE

  UNION ALL
  SELECT 'CHECK', TABLE_NAME, CONSTRAINT_NAME, ENFORCED
  FROM information_schema.TABLE_CONSTRAINTS WHERE CONSTRAINT_SCHEMA = DATABASE() AND CONSTRAINT_TYPE = 'CHECK'

  UNION ALL
  SELECT 'NOT NULL', COLUMN_METADATA.TABLE_NAME, COLUMN_METADATA.COLUMN_NAME, COLUMN_METADATA.IS_NULLABLE
  FROM information_schema.COLUMNS COLUMN_METADATA
  JOIN information_schema.TABLES tab USING (TABLE_SCHEMA, TABLE_NAME)
  WHERE COLUMN_METADATA.TABLE_SCHEMA = DATABASE() AND tab.TABLE_TYPE = 'BASE TABLE'
    AND COLUMN_METADATA.IS_NULLABLE = 'NO'

  UNION ALL
  SELECT 'INDEX', TABLE_NAME, INDEX_NAME,
         CONCAT(MAX(NON_UNIQUE), ';', MAX(INDEX_TYPE), ';', MAX(IS_VISIBLE), ';',
                GROUP_CONCAT(CONCAT(COLUMN_NAME, IF(SUB_PART IS NULL, '', CONCAT('(',SUB_PART,')')))
                             ORDER BY SEQ_IN_INDEX))
  FROM information_schema.STATISTICS WHERE TABLE_SCHEMA = DATABASE()
  GROUP BY TABLE_NAME, INDEX_NAME

  UNION ALL
  SELECT 'VIEW', TABLE_NAME, TABLE_NAME, SECURITY_TYPE
  FROM information_schema.VIEWS WHERE TABLE_SCHEMA = DATABASE()

  UNION ALL
  SELECT 'TRIGGER', EVENT_OBJECT_TABLE, TRIGGER_NAME, CONCAT(ACTION_TIMING, ' ', EVENT_MANIPULATION)
  FROM information_schema.TRIGGERS WHERE TRIGGER_SCHEMA = DATABASE()
), catalog AS (
  SELECT object_kind, table_name, object_name, expected_definition, NULL AS actual_definition
  FROM expected_schema_object
  UNION ALL
  SELECT object_kind, table_name, object_name, NULL, definition FROM actual
), compared AS (
  SELECT object_kind, table_name, object_name,
         MAX(expected_definition) AS expected_definition, MAX(actual_definition) AS actual_definition
  FROM catalog
  GROUP BY object_kind, table_name, object_name
)
SELECT IF(BINARY expected_definition = BINARY actual_definition, 'PASS', 'FAIL') AS result,
       object_kind, table_name, object_name, COALESCE(expected_definition, 'UNEXPECTED') AS expected,
       COALESCE(actual_definition, 'MISSING') AS actual
FROM compared
ORDER BY object_kind, table_name, object_name;

DROP TEMPORARY TABLE expected_schema_object;
